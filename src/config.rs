use serde::{Deserialize, Serialize};
use std::fs;
use std::path::{Path, PathBuf};

const DEFAULT_REFRESH_INTERVAL_SECS: u64 = 3;
const DEFAULT_TRAY_ICON: &str = "unitray";

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct ServiceEntry {
    pub name: String,
    pub unit: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct AppConfig {
    #[serde(default = "default_refresh_interval")]
    pub refresh_interval_secs: u64,
    #[serde(default = "default_tray_icon")]
    pub tray_icon: String,
    #[serde(default)]
    pub autostart: Option<bool>,
    #[serde(default)]
    pub services: Vec<ServiceEntry>,
}

fn default_refresh_interval() -> u64 {
    DEFAULT_REFRESH_INTERVAL_SECS
}

fn default_tray_icon() -> String {
    DEFAULT_TRAY_ICON.to_string()
}

impl Default for AppConfig {
    fn default() -> Self {
        Self {
            refresh_interval_secs: DEFAULT_REFRESH_INTERVAL_SECS,
            tray_icon: DEFAULT_TRAY_ICON.to_string(),
            autostart: Some(false),
            services: vec![
                ServiceEntry {
                    name: "MariaDB".to_string(),
                    unit: "mariadb.service".to_string(),
                },
                ServiceEntry {
                    name: "PostgreSQL".to_string(),
                    unit: "postgresql.service".to_string(),
                },
                ServiceEntry {
                    name: "Docker".to_string(),
                    unit: "docker.service".to_string(),
                },
                ServiceEntry {
                    name: "Cloudflare Tunnel".to_string(),
                    unit: "cloudflared.service".to_string(),
                },
            ],
        }
    }
}

pub fn resolve_config_path() -> Option<PathBuf> {
    if let Some(config_dir) = dirs::config_dir() {
        let user_config = config_dir.join("unitray").join("config.toml");
        if user_config.exists() {
            return Some(user_config);
        }
    }

    let system_config = Path::new("/etc/unitray/config.toml");
    if system_config.exists() {
        return Some(system_config.to_path_buf());
    }

    None
}

pub fn load_configuration() -> AppConfig {
    let Some(path) = resolve_config_path() else {
        return AppConfig::default();
    };

    let Ok(content) = fs::read_to_string(&path) else {
        eprintln!("Warning: Failed to read config file at {:?}, using defaults", path);
        return AppConfig::default();
    };

    match toml::from_str::<AppConfig>(&content) {
        Ok(config) => config,
        Err(err) => {
            eprintln!("Warning: Failed to parse TOML configuration ({}), using defaults", err);
            AppConfig::default()
        }
    }
}

pub fn get_user_config_path() -> Result<PathBuf, String> {
    let config_dir = dirs::config_dir()
        .ok_or_else(|| "Could not determine user config directory".to_string())?
        .join("unitray");
    Ok(config_dir.join("config.toml"))
}

pub fn save_configuration(config: &AppConfig) -> Result<PathBuf, String> {
    let config_path = get_user_config_path()?;
    if let Some(parent) = config_path.parent() {
        fs::create_dir_all(parent).map_err(|e| format!("Failed to create directory: {}", e))?;
    }

    let toml_string = toml::to_string_pretty(config)
        .map_err(|e| format!("Failed to serialize configuration: {}", e))?;

    let header = "# Unitray Configuration\n# Auto-generated by Unitray Settings\n\n";
    let full_content = format!("{}{}", header, toml_string);

    fs::write(&config_path, full_content)
        .map_err(|e| format!("Failed to write config file {:?}: {}", config_path, e))?;

    Ok(config_path)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_default_config_has_autostart_false() {
        let config = AppConfig::default();
        assert_eq!(config.autostart, Some(false));
    }

    #[test]
    fn test_parse_autostart_config() {
        let toml_data = r#"
            refresh_interval_secs = 5
            tray_icon = "test"
            autostart = true
            services = []
        "#;
        let config: AppConfig = toml::from_str(toml_data).unwrap();
        assert_eq!(config.autostart, Some(true));
        assert_eq!(config.refresh_interval_secs, 5);
        assert_eq!(config.tray_icon, "test");
    }

    #[test]
    fn test_backward_compatibility_without_autostart() {
        let toml_data = r#"
            refresh_interval_secs = 2
            tray_icon = "unitray"
            services = []
        "#;
        let config: AppConfig = toml::from_str(toml_data).unwrap();
        assert_eq!(config.autostart, None);
    }
}
